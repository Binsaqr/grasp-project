#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_DIR"

RULE_PATH="/etc/udev/rules.d/99-davis346.rules"
CURRENT_USER="${SUDO_USER:-${USER:-$(id -un)}}"
VENDOR_ID="${DAVIS_VENDOR_ID:-152a}"
PRODUCT_ID="${DAVIS_PRODUCT_ID:-841a}"

echo "DAVIS346 dynamic USB permission setup"
echo "====================================="
echo "Rule identity: idVendor=$VENDOR_ID idProduct=$PRODUCT_ID"
echo "No /dev/bus/usb path will be stored in the rule."
echo

TMP_RULE="$(mktemp)"
{
    echo '# DAVIS346 / iniVation event camera access'
    echo '# Generated by scripts/setup_davis_udev.sh'
    echo '# Matches stable USB identity, not transient bus/device path.'
    # MODE 0666 (world-accessible) matches the RealSense /dev/video* nodes and is
    # required for the rootless-podman container path: rootless user namespaces do
    # not map the host plugdev group, so a 0660 plugdev-only node is unreadable
    # inside the container. GROUP/uaccess are kept for host-native use.
    echo "SUBSYSTEM==\"usb\", ATTR{idVendor}==\"$VENDOR_ID\", ATTR{idProduct}==\"$PRODUCT_ID\", GROUP=\"plugdev\", MODE=\"0666\", TAG+=\"uaccess\""
} > "$TMP_RULE"

echo "Installing udev rule at $RULE_PATH"
if [ "$(id -u)" -eq 0 ]; then
    groupadd -f plugdev
    cp "$TMP_RULE" "$RULE_PATH"
    usermod -aG plugdev "$CURRENT_USER" || true
    udevadm control --reload-rules
    udevadm trigger
else
    sudo groupadd -f plugdev
    sudo cp "$TMP_RULE" "$RULE_PATH"
    sudo usermod -aG plugdev "$CURRENT_USER" || true
    sudo udevadm control --reload-rules
    sudo udevadm trigger
fi
rm -f "$TMP_RULE"

echo
echo "PASS: DAVIS udev rule installed."
echo
echo "Next steps:"
echo "1. Unplug and replug the DAVIS346 camera."
echo "2. If group membership was changed, log out/in or run:"
echo "   newgrp plugdev"
echo "3. Verify dynamic permissions:"
echo "   bash scripts/check_davis_permissions.sh"
echo
echo "Current discovery snapshot:"
python3 -m grasp_project.hardware.device_discovery --davis-check || true
